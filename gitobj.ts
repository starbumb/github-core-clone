/** Follow tag objects to the object they ultimately name (a commit, usually). */
export function peelToNonTag(lookup: ObjectLookup, oid: string): string {
  let current = oid;
  for (let depth = 0; depth < 32; depth += 1) {
    const object = lookup(current);
    if (!object || object.type !== 'tag') return current;
    current = parseTag(object.data).object;
  }
  return current;
}

/**
 * Every object reachable from `roots`. Commits in `stopAtCommits` contribute themselves and
 * their trees but not their parents (a shallow boundary). Missing objects are skipped.
 */
export function collectReachable(
  roots: Iterable<string>,
  lookup: ObjectLookup,
  stopAtCommits?: ReadonlySet<string>,
): Set<string> {
  const seen = new Set<string>();
  const queue: string[] = [];
  for (const root of roots) if (isObjectId(root)) queue.push(root);
  while (queue.length) {
    const oid = queue.pop()!;
    if (seen.has(oid)) continue;
    const object = lookup(oid);
    if (!object) continue;
    seen.add(oid);
    if (object.type === 'commit') {
      const commit = parseCommit(object.data);
      queue.push(commit.tree);
      if (!stopAtCommits?.has(oid)) for (const parent of commit.parents) queue.push(parent);
    } else if (object.type === 'tag') {
      queue.push(parseTag(object.data).object);
    } else if (object.type === 'tree') {
      for (const entry of parseTree(object.data)) {
        if (entry.mode === '160000') continue;
        queue.push(entry.oid);
      }
    }
  }
  return seen;
}

/** True when `ancestor` is reachable from `descendant` by following commit parents (or equal). */
export function isAncestor(lookup: ObjectLookup, ancestor: string, descendant: string): boolean {
  const target = peelToNonTag(lookup, ancestor);
  const start = peelToNonTag(lookup, descendant);
  if (target === start) return true;
  const seen = new Set<string>();
  const queue = [start];
  while (queue.length) {
    const oid = queue.pop()!;
    if (seen.has(oid)) continue;
    seen.add(oid);
    const object = lookup(oid);
    if (!object || object.type !== 'commit') continue;
    for (const parent of parseCommit(object.data).parents) {
      if (parent === target) return true;
      queue.push(parent);
    }
  }
  return false;
}

/** A best common ancestor of two commits (the first one a breadth-first walk from `a` finds in `b`'s history). */
export function mergeBase(lookup: ObjectLookup, a: string, b: string): string | null {
  const aCommit = peelToNonTag(lookup, a);
  const bCommit = peelToNonTag(lookup, b);
  if (aCommit === bCommit) return aCommit;
  const bAncestors = new Set<string>();
  const stack = [bCommit];
  while (stack.length) {
    const oid = stack.pop()!;
    if (bAncestors.has(oid)) continue;
    bAncestors.add(oid);
    const object = lookup(oid);
    if (object?.type === 'commit') for (const parent of parseCommit(object.data).parents) stack.push(parent);
  }
  const queue = [aCommit];
  const seen = new Set<string>();
  while (queue.length) {
    const oid = queue.shift()!;
    if (seen.has(oid)) continue;
    seen.add(oid);
    if (bAncestors.has(oid)) return oid;
    const object = lookup(oid);
    if (object?.type === 'commit') for (const parent of parseCommit(object.data).parents) queue.push(parent);
  }
  return null;
}

/** Flatten a tree into path -> blob oid (gitlinks and trees themselves excluded). */
export function flattenTree(lookup: ObjectLookup, treeOid: string, prefix = '', out = new Map<string, string>()): Map<string, string> {
  const object = lookup(treeOid);
  if (!object || object.type !== 'tree') return out;
  for (const entry of parseTree(object.data)) {
    const path = prefix === '' ? entry.name : `${prefix}/${entry.name}`;
    if (entry.mode === '40000') flattenTree(lookup, entry.oid, path, out);
    else if (entry.mode !== '160000') out.set(path, entry.oid);
  }
  return out;
}

/** The tree oid of a commit-ish (peels tags; a tree oid passes through). */
export function treeOf(lookup: ObjectLookup, oid: string): string | null {
  const peeled = peelToNonTag(lookup, oid);
  const object = lookup(peeled);
  if (!object) return null;
  if (object.type === 'tree') return peeled;
  if (object.type === 'commit') return parseCommit(object.data).tree;
  return null;
}

/** Set `path` to `blobOid` (or remove it when null) in a tree, creating subtrees as needed; returns the new tree oid. */
export function updateTreePath(
  store: Map<string, GitObject>,
  treeOid: string | null,
  segments: readonly string[],
  blobOid: string | null,
): string {
  const put = (type: GitObjectType, data: Buffer): string => {
    const oid = hashObject(type, data);
    if (!store.has(oid)) store.set(oid, { type, data });
    return oid;
  };
  const head = segments[0]!;
  const rest = segments.slice(1);
  const existing = treeOid === null ? [] : parseTree(store.get(treeOid)?.data ?? Buffer.alloc(0));
  const kept = existing.filter((entry) => entry.name !== head);
  if (rest.length === 0) {
    if (blobOid !== null) kept.push({ mode: '100644', name: head, oid: blobOid });
  } else {
    const child = existing.find((entry) => entry.name === head && entry.mode === '40000');
    const childOid = updateTreePath(store, child?.oid ?? null, rest, blobOid);
    // An emptied subtree disappears, as git has no empty directories.
    const childEntries = parseTree(store.get(childOid)?.data ?? Buffer.alloc(0));
    if (childEntries.length > 0) kept.push({ mode: '40000', name: head, oid: childOid });
  }
  return put('tree', buildTree(kept));
}

/** The blob oid at `segments` under a tree, or null. */
export function lookupTreePath(lookup: ObjectLookup, treeOid: string, segments: readonly string[]): { oid: string; mode: string } | null {
  let current = treeOid;
  for (let index = 0; index < segments.length; index += 1) {
    const object = lookup(current);
    if (!object || object.type !== 'tree') return null;
    const entry = parseTree(object.data).find((candidate) => candidate.name === segments[index]);
    if (!entry) return null;
    if (index === segments.length - 1) return { oid: entry.oid, mode: entry.mode };
    if (entry.mode !== '40000') return null;
    current = entry.oid;
  }
  return null;
}
